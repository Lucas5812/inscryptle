BEGIN TRANSACTION;
CREATE TABLE IF NOT EXISTS Caracteristicas (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT NOT NULL UNIQUE,
    Description TEXT
);
CREATE TABLE IF NOT EXISTS Carta_Caracteristica (
    CartaID INTEGER NOT NULL,
    CaracteristicaID INTEGER NOT NULL,

    PRIMARY KEY (CartaID, CaracteristicaID),

    FOREIGN KEY (CartaID) REFERENCES Cartas(ID),
    FOREIGN KEY (CaracteristicaID) REFERENCES Caracteristicas(ID)
);
CREATE TABLE IF NOT EXISTS Carta_Sigilo (
    CartaID INTEGER NOT NULL,
    SigiloID INTEGER NOT NULL,

    PRIMARY KEY (CartaID, SigiloID),

    FOREIGN KEY (CartaID) REFERENCES Cartas(ID),
    FOREIGN KEY (SigiloID) REFERENCES Sigilos(ID)
);
CREATE TABLE IF NOT EXISTS Carta_Tribo (
    CartaID INTEGER NOT NULL,
    TriboID INTEGER NOT NULL,

    PRIMARY KEY (CartaID, TriboID),

    FOREIGN KEY (CartaID) REFERENCES Cartas(ID),
    FOREIGN KEY (TriboID) REFERENCES Tribos(ID)
);
CREATE TABLE IF NOT EXISTS Cartas (
    ID INTEGER PRIMARY KEY,
    Name TEXT NOT NULL,
    Power TEXT NOT NULL,
    Health INTEGER NOT NULL,
    CostAmount INTEGER NOT NULL,
    CostType TEXT NOT NULL
        CHECK (CostType IN ('sangue', 'ossos', 'nenhum'))
);
CREATE TABLE IF NOT EXISTS DesafiosDiarios (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    Date TEXT NOT NULL UNIQUE,
    CartaID INTEGER NOT NULL,

    FOREIGN KEY (CartaID) REFERENCES Cartas(ID)
);
CREATE TABLE IF NOT EXISTS Sigilos (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT NOT NULL UNIQUE,
    Description TEXT
);
CREATE TABLE IF NOT EXISTS Tribos (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT NOT NULL UNIQUE,
    Description TEXT
);
